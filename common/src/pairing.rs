//! Pairing protocol and the receiver-side state machine (M7 UI).
//!
//! Messages are single-line UTF-8 datagrams exchanged over UDP on the
//! receiver's advertised `pair_port`:
//!
//! ```text
//! PAIR1|REQ|host_id|host_name          host -> receiver, first contact
//! PAIR1|RESUME|host_id|host_name       host -> receiver, previously paired
//! PAIR1|CHALLENGE|code                 receiver -> host, 6-digit code to show
//! PAIR1|ACCEPT|code|token_hex|key_hex  receiver -> host, after the user allows
//! PAIR1|REJECT|reason                  receiver -> host
//! ```
//!
//! ## Security note (prototype)
//!
//! The session key and token are generated by a small non-cryptographic PRNG
//! seeded from the clock and the process id. That is fine for this milestone
//! (the video stream is still unencrypted); replace [`random_key`] with an OS
//! CSPRNG (`getrandom`/`BCryptGenRandom`) before the key protects real traffic.

use std::time::{SystemTime, UNIX_EPOCH};

/// First field of a pairing line.
pub const PAIR_MAGIC: &str = "PAIR1";
/// Length of the agreed session key.
pub const KEY_LEN: usize = 32;

/// One pairing protocol message.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PairMsg {
    /// First contact from a host that is not paired yet.
    Request { host_id: String, host_name: String },
    /// Contact from a host already in the receiver's store (one-click confirm).
    Resume { host_id: String, host_name: String },
    /// Receiver asks the host to display this code for visual comparison.
    Challenge { code: String },
    /// Receiver allowed the host. `token` keys input injection; `key` is for
    /// the next milestone (video encryption).
    Accept { code: String, token: u64, key: [u8; KEY_LEN] },
    /// Receiver denied the host.
    Reject { reason: String },
}

impl PairMsg {
    /// Render the message as a single-line datagram payload.
    pub fn encode(&self) -> String {
        match self {
            PairMsg::Request { host_id, host_name } => {
                format!("{PAIR_MAGIC}|REQ|{}|{}", sanitize(host_id), sanitize(host_name))
            }
            PairMsg::Resume { host_id, host_name } => format!(
                "{PAIR_MAGIC}|RESUME|{}|{}",
                sanitize(host_id),
                sanitize(host_name)
            ),
            PairMsg::Challenge { code } => {
                format!("{PAIR_MAGIC}|CHALLENGE|{}", sanitize(code))
            }
            PairMsg::Accept { code, token, key } => format!(
                "{PAIR_MAGIC}|ACCEPT|{}|{:016x}|{}",
                sanitize(code),
                token,
                to_hex(key)
            ),
            PairMsg::Reject { reason } => {
                format!("{PAIR_MAGIC}|REJECT|{}", sanitize(reason))
            }
        }
    }

    /// Parse a datagram payload. `None` means "not a valid pairing message".
    pub fn decode(text: &str) -> Option<Self> {
        let mut parts = text.trim().split('|');
        if parts.next()? != PAIR_MAGIC {
            return None;
        }
        let kind = parts.next()?;
        let msg = match kind {
            "REQ" | "RESUME" => {
                let host_id = parts.next()?.to_string();
                let host_name = parts.next()?.to_string();
                if parts.next().is_some() || host_id.is_empty() {
                    return None;
                }
                if kind == "REQ" {
                    PairMsg::Request { host_id, host_name }
                } else {
                    PairMsg::Resume { host_id, host_name }
                }
            }
            "CHALLENGE" => {
                let code = parts.next()?.to_string();
                if parts.next().is_some() || code.is_empty() {
                    return None;
                }
                PairMsg::Challenge { code }
            }
            "ACCEPT" => {
                let code = parts.next()?.to_string();
                let token_hex = parts.next()?;
                let key_hex = parts.next()?;
                if parts.next().is_some() {
                    return None;
                }
                let token = u64::from_str_radix(token_hex, 16).ok()?;
                let key_bytes = from_hex(key_hex)?;
                if key_bytes.len() != KEY_LEN {
                    return None;
                }
                let mut key = [0u8; KEY_LEN];
                key.copy_from_slice(&key_bytes);
                PairMsg::Accept { code, token, key }
            }
            "REJECT" => {
                let reason = parts.next()?.to_string();
                if parts.next().is_some() {
                    return None;
                }
                PairMsg::Reject { reason }
            }
            _ => return None,
        };
        Some(msg)
    }
}

/// Receiver state machine. The GUI feeds received [`PairMsg`]s in with
/// [`PairingMachine::on_request`] and calls [`PairingMachine::allow`] /
/// [`PairingMachine::deny`] when the user clicks a button.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PairState {
    Idle,
    AwaitingAllow {
        code: String,
        host_id: String,
        host_name: String,
        resume: bool,
        known: Option<(u64, [u8; KEY_LEN])>,
    },
    Accepted {
        host_id: String,
        host_name: String,
        token: u64,
        key: [u8; KEY_LEN],
    },
    Rejected {
        reason: String,
    },
}

pub struct PairingMachine {
    state: PairState,
}

impl Default for PairingMachine {
    fn default() -> Self {
        Self::new()
    }
}

impl PairingMachine {
    pub fn new() -> Self {
        Self {
            state: PairState::Idle,
        }
    }

    pub fn state(&self) -> &PairState {
        &self.state
    }

    /// The pending request, if the UI should show an Allow/Deny dialog.
    pub fn pending(&self) -> Option<(&str, &str, bool)> {
        match &self.state {
            PairState::AwaitingAllow {
                host_id,
                host_name,
                resume,
                ..
            } => Some((host_id, host_name, *resume)),
            _ => None,
        }
    }

    /// Handle an incoming REQ/RESUME. Always moves to `AwaitingAllow` and
    /// returns the Challenge the host should display.
    ///
    /// `known` is the stored `(token, key)` for a returning host, if any.
    pub fn on_request(
        &mut self,
        host_id: &str,
        host_name: &str,
        known: Option<(u64, [u8; KEY_LEN])>,
    ) -> PairMsg {
        let code = random_code();
        self.state = PairState::AwaitingAllow {
            code: code.clone(),
            host_id: sanitize(host_id),
            host_name: sanitize(host_name),
            resume: known.is_some(),
            known,
        };
        PairMsg::Challenge { code }
    }

    /// The user clicked Allow. Reuses stored credentials for a resume, or
    /// generates a fresh token and 32-byte key for a new host.
    pub fn allow(&mut self) -> Option<PairMsg> {
        let PairState::AwaitingAllow {
            code,
            host_id,
            host_name,
            known,
            ..
        } = &self.state
        else {
            return None;
        };
        let (token, key) = match known {
            Some((token, key)) => (*token, *key),
            None => (random_token(), random_key()),
        };
        let msg = PairMsg::Accept {
            code: code.clone(),
            token,
            key,
        };
        self.state = PairState::Accepted {
            host_id: host_id.clone(),
            host_name: host_name.clone(),
            token,
            key,
        };
        Some(msg)
    }

    /// The user clicked Deny.
    pub fn deny(&mut self, reason: &str) -> Option<PairMsg> {
        if !matches!(self.state, PairState::AwaitingAllow { .. }) {
            return None;
        }
        let reason = sanitize(reason);
        self.state = PairState::Rejected {
            reason: reason.clone(),
        };
        Some(PairMsg::Reject { reason })
    }

    /// Drop any current dialog (e.g. after the host disconnected).
    pub fn reset(&mut self) {
        self.state = PairState::Idle;
    }
}

/// Lowercase hex, no separators.
pub fn to_hex(bytes: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(HEX[(byte >> 4) as usize] as char);
        out.push(HEX[(byte & 0x0f) as usize] as char);
    }
    out
}

/// Decode lowercase/uppercase hex. Returns `None` on odd length or bad digit.
pub fn from_hex(text: &str) -> Option<Vec<u8>> {
    if text.len() % 2 != 0 {
        return None;
    }
    let mut out = Vec::with_capacity(text.len() / 2);
    let bytes = text.as_bytes();
    let mut index = 0;
    while index < bytes.len() {
        let hi = hex_digit(bytes[index])?;
        let lo = hex_digit(bytes[index + 1])?;
        out.push((hi << 4) | lo);
        index += 2;
    }
    Some(out)
}

fn hex_digit(byte: u8) -> Option<u8> {
    match byte {
        b'0'..=b'9' => Some(byte - b'0'),
        b'a'..=b'f' => Some(byte - b'a' + 10),
        b'A'..=b'F' => Some(byte - b'A' + 10),
        _ => None,
    }
}

fn sanitize(value: &str) -> String {
    value
        .chars()
        .map(|c| if c == '|' || c.is_control() { '_' } else { c })
        .collect()
}

// --- Prototype randomness (see the module-level security note) ---------------

fn seed() -> u64 {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_nanos() as u64)
        .unwrap_or(0x9E37_79B9_7F4A_7C15);
    let pid = std::process::id() as u64;
    let stack = &nanos as *const u64 as u64;
    nanos ^ pid.rotate_left(17) ^ stack.rotate_left(31) ^ 0xD1B5_4A32_D192_ED03
}

fn splitmix64(state: &mut u64) -> u64 {
    *state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
    let mut z = *state;
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// 32 random bytes for the session key.
pub fn random_key() -> [u8; KEY_LEN] {
    let mut state = seed();
    let mut key = [0u8; KEY_LEN];
    for chunk in key.chunks_mut(8) {
        let value = splitmix64(&mut state);
        chunk.copy_from_slice(&value.to_be_bytes()[..chunk.len()]);
    }
    key
}

/// A non-zero random token for input anti-spoofing.
pub fn random_token() -> u64 {
    let mut state = seed();
    let token = splitmix64(&mut state);
    if token == 0 {
        1
    } else {
        token
    }
}

/// A six-digit code shown on both screens.
pub fn random_code() -> String {
    let mut state = seed();
    format!("{:06}", splitmix64(&mut state) % 1_000_000)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn key() -> [u8; KEY_LEN] {
        let mut key = [0u8; KEY_LEN];
        for (index, byte) in key.iter_mut().enumerate() {
            *byte = index as u8;
        }
        key
    }

    #[test]
    fn hex_roundtrip() {
        let bytes: Vec<u8> = (0..=255u8).collect();
        let text = to_hex(&bytes);
        assert_eq!(text.len(), 512);
        assert_eq!(from_hex(&text), Some(bytes));
        assert_eq!(from_hex("0"), None);
        assert_eq!(from_hex("zz"), None);
    }

    #[test]
    fn request_and_challenge_roundtrip() {
        let msg = PairMsg::Request {
            host_id: "host-1".into(),
            host_name: "Saravana laptop".into(),
        };
        assert_eq!(PairMsg::decode(&msg.encode()), Some(msg));

        let msg = PairMsg::Challenge {
            code: "012345".into(),
        };
        assert_eq!(PairMsg::decode(&msg.encode()), Some(msg));
    }

    #[test]
    fn accept_roundtrip_carries_key_and_token() {
        let msg = PairMsg::Accept {
            code: "123456".into(),
            token: 0xDEAD_BEEF_1234_5678,
            key: key(),
        };
        let decoded = PairMsg::decode(&msg.encode()).expect("accept decodes");
        assert_eq!(decoded, msg);
        if let PairMsg::Accept { token, key: k, .. } = decoded {
            assert_eq!(token, 0xDEAD_BEEF_1234_5678);
            assert_eq!(k, key());
        }
    }

    #[test]
    fn reject_roundtrip() {
        let msg = PairMsg::Reject {
            reason: "user denied".into(),
        };
        assert_eq!(PairMsg::decode(&msg.encode()), Some(msg));
    }

    #[test]
    fn decode_rejects_bad_input() {
        assert_eq!(PairMsg::decode("nope"), None);
        assert_eq!(PairMsg::decode("PAIR1|UNKNOWN|x"), None);
        assert_eq!(PairMsg::decode("PAIR1|ACCEPT|123456|nothex|00"), None);
        assert_eq!(PairMsg::decode("PAIR1|ACCEPT|123456|0000000000000001|00"), None);
        assert_eq!(PairMsg::decode("PAIR1|REQ|onlyid"), None);
    }

    #[test]
    fn machine_request_then_allow() {
        let mut machine = PairingMachine::new();
        let challenge = machine.on_request("host-1", "Laptop", None);
        let code = match &challenge {
            PairMsg::Challenge { code } => code.clone(),
            other => panic!("expected challenge, got {other:?}"),
        };
        assert_eq!(code.len(), 6);
        assert!(code.chars().all(|c| c.is_ascii_digit()));
        assert_eq!(machine.pending(), Some(("host-1", "Laptop", false)));

        let accept = machine.allow().expect("allow returns a message");
        match accept {
            PairMsg::Accept {
                code: accepted_code,
                token,
                key,
            } => {
                assert_eq!(accepted_code, code);
                assert_ne!(token, 0);
                assert_eq!(key.len(), KEY_LEN);
            }
            other => panic!("expected accept, got {other:?}"),
        }
        assert!(matches!(machine.state(), PairState::Accepted { .. }));
        assert_eq!(machine.pending(), None);
    }

    #[test]
    fn machine_resume_reuses_stored_credentials() {
        let stored = (0x1122_3344_5566_7788, key());
        let mut machine = PairingMachine::new();
        machine.on_request("host-1", "Laptop", Some(stored));
        assert_eq!(machine.pending(), Some(("host-1", "Laptop", true)));
        let accept = machine.allow().expect("resume allows");
        match accept {
            PairMsg::Accept { token, key: k, .. } => {
                assert_eq!(token, stored.0);
                assert_eq!(k, stored.1);
            }
            other => panic!("expected accept, got {other:?}"),
        }
    }

    #[test]
    fn machine_deny() {
        let mut machine = PairingMachine::new();
        machine.on_request("host-1", "Laptop", None);
        let reject = machine.deny("user denied").expect("deny returns a message");
        assert_eq!(
            reject,
            PairMsg::Reject {
                reason: "user denied".into()
            }
        );
        assert!(matches!(machine.state(), PairState::Rejected { .. }));
        assert_eq!(machine.allow(), None);
    }

    #[test]
    fn machine_allow_without_request_is_none() {
        let mut machine = PairingMachine::new();
        assert_eq!(machine.allow(), None);
        assert_eq!(machine.deny("x"), None);
    }
}
